# Map standard 2-letter codes to NLLB FLORES-200 codes
NLLB_CODE_MAPPING = {
    "hi": "hin_Deva",  # Hindi (Devanagari script)
    "es": "spa_Latn",  # Spanish
    "fr": "fra_Latn",  # French
    "de": "deu_Latn",  # German
    "zh": "zho_Hans",  # Chinese (Simplified)
    "ar": "arb_Arab",  # Arabic
    "it": "ita_Latn",  # Italian
    "pt": "por_Latn",  # Portuguese
    # Add any other languages your dataset might contain here!
}

def translate_to_english(text, default_language="hin_Deva"):
    # 1. Automatically detect the 2-letter language code
    try:
        detected_iso = detect(text)  # Returns strings like 'hi', 'es', 'fr'
        # Get the corresponding NLLB code, fallback to default if not mapped
        source_language = NLLB_CODE_MAPPING.get(detected_iso, default_language)
    except Exception:
        # Fallback if text is too short or contains only numbers/emojis
        source_language = default_language

    # 2. Update the tokenizer language code dynamically
    translation_tokenizer.src_lang = source_language

    inputs = translation_tokenizer(
        text,
        return_tensors="pt",
        max_length=512,
        truncation=True
    )

    inputs = {key: value.to(device) for key, value in inputs.items()}

    with torch.no_grad():
        translated_tokens = translation_model.generate(
            **inputs,
            forced_bos_token_id=translation_tokenizer.convert_tokens_to_ids("eng_Latn"),
            max_length=512
        )

    translated_text = translation_tokenizer.batch_decode(
        translated_tokens,
        skip_special_tokens=True
    )[0]

    return translated_text

