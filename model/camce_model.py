def summarize_text(text):

    inputs = tokenizer(
        text,
        max_length=512,
        truncation=True,
        return_tensors="pt"
    )

    inputs = {
        key: value.to(device)
        for key, value in inputs.items()
    }

    with torch.no_grad():

        summary_ids = model.generate(

            **inputs,

            max_length=150,

            min_length=30,

            num_beams=4,

            length_penalty=2.0,

            early_stopping=True
        )

    summary = tokenizer.decode(
            summary_ids[0],
            skip_special_tokens=True
        )

    return summary

def camce_summarize(text):

    # Step 1: Translate to English

    english_text = translate_to_english(
            text
        )


    # Step 2: Summarize English text

    summary = summarize_text(
            english_text
        )


    return {
        "original_text": text,
        "english_text": english_text,
        "summary": summary
    }

