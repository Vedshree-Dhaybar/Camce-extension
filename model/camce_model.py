def tokenize_function(examples):

    inputs = tokenizer(
        examples["article"],
        max_length=1024,
        truncation=True
    )

    labels = tokenizer(
        text_target=examples["highlights"],
        max_length=128,
        truncation=True
    )

    inputs["labels"] = labels["input_ids"]

    return inputs

